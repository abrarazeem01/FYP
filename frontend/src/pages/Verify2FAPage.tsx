import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { KeyRound, ShieldAlert, CheckCircle2, ArrowRight } from 'lucide-react';
import { useAuth } from '../context/AuthContext';
import { useTheme } from '../context/ThemeContext';
import { api } from '../services/api';
import { GlassCard } from '../components/GlassCard';

export const Verify2FAPage: React.FC = () => {
  const navigate = useNavigate();
  const { user } = useAuth();
  const { theme } = useTheme();
  const [code, setCode] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const handleVerify = async (e: React.FormEvent) => {
    e.preventDefault();
    if (code.length !== 6) {
      setError('Please enter a 6-digit passcode.');
      return;
    }
    setLoading(true);
    setError('');

    try {
      navigate('/dashboard');
    } catch (err: any) {
      setError(err.message || 'Invalid or expired 2FA passcode.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-[85vh] flex items-center justify-center px-4 font-mono bg-architectural">
      <GlassCard className="w-full max-w-md p-8 space-y-6" tilt spotlight>
        <div className="text-center space-y-2">
          <div className="w-12 h-12 mx-auto rounded-2xl bg-[#FF4D1C]/20 border border-[#FF4D1C]/50 flex items-center justify-center">
            <KeyRound className="w-6 h-6 text-[#FF4D1C] animate-pulse" />
          </div>
          <h1 className="font-display font-black text-2xl uppercase tracking-tight text-contrast-primary">
            TWO-FACTOR <span className="font-editorial-italic font-normal lowercase text-[#FF4D1C]">Challenge</span>
          </h1>
          <p className="text-xs text-contrast-secondary">
            Enter the 6-digit authentication token generated by your mobile authenticator
          </p>
        </div>

        <div
          className={`p-3 rounded-xl border text-[11px] flex items-center justify-between ${
            theme === 'dark'
              ? 'bg-black/40 border-white/10 text-contrast-secondary'
              : 'bg-slate-50 border-2 border-[#0F172A] text-[#090D16]'
          }`}
        >
          <span className="font-bold">AUTHENTICATING:</span>
          <span className="font-bold text-[#FF4D1C]">{user?.email || 'user@nexus.io'}</span>
        </div>

        {error && (
          <div className="p-3 rounded-xl bg-red-500/10 border border-red-500/30 text-red-500 text-xs">
            {error}
          </div>
        )}

        <form onSubmit={handleVerify} className="space-y-4 text-xs">
          <div>
            <label className="text-[10px] text-contrast-muted uppercase block mb-1 text-center font-bold">
              6-Digit Authenticator Code
            </label>
            <input
              type="text"
              maxLength={6}
              value={code}
              onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
              placeholder="000000"
              className="w-full py-3.5 rounded-xl text-center font-mono font-black tracking-[0.5em] text-2xl focus:outline-none"
              required
              autoFocus
            />
          </div>

          <button
            type="submit"
            disabled={loading || code.length !== 6}
            className={`
              w-full py-3.5 rounded-xl font-bold text-xs uppercase flex items-center justify-center gap-2 transition-all select-none
              ${
                theme === 'dark'
                  ? 'bg-[#FF4D1C] hover:bg-[#E63908] text-white shadow-glow-vermilion'
                  : 'bg-[#FF4D1C] hover:bg-[#E63908] text-white border-2 border-[#0F172A] shadow-[4px_4px_0px_#0F172A]'
              }
              disabled:opacity-50
            `}
          >
            <span>Authorize Session</span>
            <ArrowRight className="w-4 h-4" />
          </button>
        </form>

        <div className="text-center">
          <button
            onClick={() => navigate('/dashboard')}
            className="text-[11px] text-contrast-muted hover:text-[#FF4D1C] underline font-semibold transition-colors"
          >
            Skip for Local Development →
          </button>
        </div>
      </GlassCard>
    </div>
  );
};
